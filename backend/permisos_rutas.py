"""
Permiso que exige cada ruta de la API (además de tener sesión).

La regla es la misma que aplica el frontend: una ruta se permite si el usuario puede abrir alguna
de las pantallas que la usan. Por eso una ruta compartida acepta varios permisos (por ejemplo, la
búsqueda de productos la usan Ventas, Presupuestos, Stock, Proveedores y Reportes). Los roles
administrador pasan siempre.

    ()     cualquier usuario con sesión
    None   la ruta declara su propio requiere_permiso(...) en server.py

Las rutas que cambian datos piden el permiso de la acción (productos.crear, stock.entrada,
ventas.anular...), el mismo con el que las pantallas muestran el botón. Algunas acciones se controlan
dentro de la ruta según lo que cambia: el precio en una venta (ventas.modificar_precio), el precio de un
producto (productos.modificar_precio), el descuento de un cliente (clientes.modificar_descuento) y si la
venta lleva el descuento del cliente (ventas.aplicar_descuento). Marcas, categorías y los productos de un
proveedor siguen con el permiso de ver: no tienen uno propio. Al pasar a este esquema, la migración 0004
le dio a cada rol las acciones que las pantallas ya le dejaban hacer sin pedir el permiso.

Una ruta nueva sin entrada acá responde 403 (y tests/test_seguridad_rutas.py falla): hay que
agregarla con los permisos de las pantallas que la llamen.
"""

